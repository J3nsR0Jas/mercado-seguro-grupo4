    ('empleado.essalud@essalud.pe', 'essalud', 'empleado')
) AS r(correo_patron, modulo, rol)
  ON u.correo LIKE r.correo_patron
ON CONFLICT (id_usuario, modulo) DO UPDATE SET rol = EXCLUDED.rol;

