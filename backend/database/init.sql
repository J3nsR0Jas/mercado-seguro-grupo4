BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(160) NOT NULL UNIQUE,
    contrasena_hash TEXT NOT NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    modulo VARCHAR(30) NOT NULL CHECK (modulo IN ('mercado', 'pnp', 'essalud')),
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('cliente', 'administrador', 'empleado')),
    PRIMARY KEY (id_usuario, modulo)
);

CREATE TABLE IF NOT EXISTS comerciantes_interesados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    razon_social VARCHAR(150) NOT NULL,
    producto VARCHAR(120) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    direccion VARCHAR(220) NOT NULL,
    puesto VARCHAR(30) NOT NULL,
    area_m2 NUMERIC(8,2) NOT NULL DEFAULT 1 CHECK (area_m2 > 0),
    dias INTEGER NOT NULL DEFAULT 1 CHECK (dias > 0),
    alto_consumo BOOLEAN NOT NULL DEFAULT FALSE,
    monto_calculado NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (monto_calculado >= 0),
    estado_pago VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_pago IN ('pendiente', 'pagado', 'exonerado')),
    estado VARCHAR(30) NOT NULL DEFAULT 'registrado'
        CHECK (estado IN ('registrado', 'aprobado', 'rechazado', 'activo')),
    codigo_seguimiento VARCHAR(50) NOT NULL UNIQUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS denuncias_digitales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_seguimiento VARCHAR(50) NOT NULL UNIQUE,
    dni_denunciante VARCHAR(12) NOT NULL,
    tipo_delito VARCHAR(100) NOT NULL,
    lugar_incidente VARCHAR(220) NOT NULL,
    detalle_denuncia TEXT NOT NULL,
    hay_lesionados BOOLEAN NOT NULL DEFAULT FALSE,
    estado VARCHAR(30) NOT NULL DEFAULT 'registrado'
        CHECK (estado IN ('registrado', 'en investigación', 'derivado', 'atendido')),
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id),
    id_empleado_asignado BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    id_comerciante BIGINT REFERENCES comerciantes_interesados(id) ON DELETE SET NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS citas_essalud (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_seguimiento VARCHAR(50) NOT NULL UNIQUE,
    numero_asegurado VARCHAR(20) NOT NULL,
    nombre_paciente VARCHAR(120) NOT NULL,
    sede VARCHAR(120) NOT NULL,
    tipo_asegurado VARCHAR(30) NOT NULL
        CHECK (tipo_asegurado IN ('titular', 'derechohabiente')),
    especialidad VARCHAR(100) NOT NULL DEFAULT 'Medicina general',
    motivo TEXT,
    fecha_cita TIMESTAMPTZ,
    monto_calculado NUMERIC(10,2) NOT NULL DEFAULT 10 CHECK (monto_calculado >= 0),
    estado_pago VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_pago IN ('pendiente', 'pagado', 'exonerado')),
    canal_pago VARCHAR(30),
    fecha_pago TIMESTAMPTZ,
    estado VARCHAR(30) NOT NULL DEFAULT 'registrado'
        CHECK (estado IN ('registrado', 'confirmada', 'atendida', 'cancelada')),
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id),
    id_empleado_asignado BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    id_denuncia BIGINT REFERENCES denuncias_digitales(id) ON DELETE SET NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_operacion VARCHAR(60) NOT NULL UNIQUE,
    id_registro BIGINT NOT NULL REFERENCES citas_essalud(id) ON DELETE CASCADE,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id),
    canal VARCHAR(30) NOT NULL DEFAULT 'pasarela',
    metodo VARCHAR(30) NOT NULL,
    proveedor_billetera VARCHAR(40),
    marca_tarjeta VARCHAR(30),
    referencia VARCHAR(40) NOT NULL,
    monto NUMERIC(10,2) NOT NULL CHECK (monto >= 0),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('aprobado', 'rechazado')),
    motivo_rechazo TEXT,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pagos_mercado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comerciante BIGINT NOT NULL UNIQUE REFERENCES comerciantes_interesados(id) ON DELETE CASCADE,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    codigo_operacion VARCHAR(60) NOT NULL UNIQUE,
    metodo VARCHAR(30) NOT NULL CHECK (metodo = 'tarjeta_demo'),
    estado VARCHAR(20) NOT NULL CHECK (estado = 'simulado'),
    monto NUMERIC(10,2) NOT NULL CHECK (monto >= 0),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_comerciantes_usuario
    ON comerciantes_interesados(id_usuario, fecha_registro DESC);
CREATE INDEX IF NOT EXISTS idx_denuncias_usuario
    ON denuncias_digitales(id_usuario, fecha_registro DESC);
CREATE INDEX IF NOT EXISTS idx_denuncias_comerciante
    ON denuncias_digitales(id_comerciante);
CREATE INDEX IF NOT EXISTS idx_citas_usuario
    ON citas_essalud(id_usuario, fecha_registro DESC);
CREATE INDEX IF NOT EXISTS idx_citas_denuncia
    ON citas_essalud(id_denuncia);
CREATE UNIQUE INDEX IF NOT EXISTS idx_cita_una_por_denuncia
    ON citas_essalud(id_denuncia) WHERE id_denuncia IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_pagos_registro
    ON pagos(id_registro, fecha_registro DESC);

