SELECT u.id, r.modulo, r.rol
FROM usuarios u
JOIN (VALUES
    ('cliente%@correo.com', 'mercado', 'cliente'),
    ('cliente%@correo.com', 'pnp', 'cliente'),
    ('cliente%@correo.com', 'essalud', 'cliente'),
    ('admin@mercado.pe', 'mercado', 'administrador'),
    ('empleado.mercado@mercado.pe', 'mercado', 'empleado'),
