-- Pagos demostrativos de puestos: nunca almacenar tarjeta, vencimiento ni CVV.
CREATE TABLE IF NOT EXISTS pagos_mercado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comerciante BIGINT NOT NULL UNIQUE REFERENCES comerciantes_interesados(id) ON DELETE CASCADE,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    codigo_operacion VARCHAR(60) NOT NULL UNIQUE,
    metodo VARCHAR(30) NOT NULL CHECK (metodo = 'tarjeta_demo'),
    estado VARCHAR(20) NOT NULL CHECK (estado = 'simulado'),
    monto NUMERIC(10,2) NOT NULL CHECK (monto >= 0),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
